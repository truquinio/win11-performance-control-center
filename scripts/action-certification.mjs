import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = relative => fs.readFileSync(path.join(root, relative), "utf8");
const catalog = read("src/App/Core/ActionCatalog.cs");
const executor = read("src/App/Core/ActionExecutor.cs");
// Trace interactive follow-ups across the authored UI modules, never the
// generated catalog (which would incorrectly certify every action as visible).
const frontend = [
  "src/Frontend/app.ts",
  "src/Frontend/components/action-results.ts"
].map(read).join("\n");
const html = read("src/Frontend/index.html");
const definitions = [...catalog.matchAll(/new ActionDefinition\("([^"]+)"/g)];
const execBlock = executor.match(/return action\.Id switch\s*\{([\s\S]*?)_ => throw/)?.[1] ?? "";
const executable = new Set([...execBlock.matchAll(/"([^"]+)"\s*=>/g)].map(m => m[1]));
const generated = JSON.parse(read("src/Frontend/generated/action-catalog.json"));
const demo = new Set(generated.map(action => action.id));
const modules = read("src/Frontend/module-definitions.ts");
const moduleBlock = modules.match(/const moduleDefinitions:[\s\S]*?= \{([\s\S]*?)\n\};/)?.[1] ?? "";
const moduleActions = new Set([...moduleBlock.matchAll(/"([a-z][a-z0-9.-]+)"/g)].map(m => m[1]));
const directActions = new Set([...html.matchAll(/data-action="([^"]+)"/g)].map(m => m[1]));
// Module definitions moved to their own file in v2. Scan the full UI source
// for explicit contextual follow-ups instead of slicing from a deleted marker.
const followupActions = new Set([...frontend
  .matchAll(/"([a-z][a-z0-9.-]+)"/g)].map(m => m[1]));
const rows = definitions.map((found, index) => {
  const next = definitions[index + 1]?.index ?? catalog.length;
  const fragment = catalog.slice(found.index, next);
  const category = fragment.match(/ActionCategory\.(\w+)/)?.[1];
  const mode = fragment.match(/ActionMode\.(READ|DRY_RUN|WRITE)/)?.[1];
  if (!category || !mode) throw new Error("Missing category/mode for " + found[1]);
  return {
    id: found[1], category, mode,
    dispatch: executable.has(found[1]),
    demo: demo.has(found[1]),
    ui: moduleActions.has(found[1]) ? "module" :
      directActions.has(found[1]) ? "dashboard" :
      followupActions.has(found[1]) ? "follow-up" : "untraced"
  };
});
const missing = rows.filter(row => !row.dispatch || !row.demo || row.ui === "untraced");
if (rows.length === 0 || missing.length || demo.size !== rows.length ||
    executable.size !== rows.length) {
  throw new Error("Catalog parity/inventory mismatch: " + JSON.stringify({
    total: rows.length, demo: demo.size, dispatch: executable.size, missing
  }));
}
const counts = Object.groupBy(rows, row => row.mode);
const lines = [
  "# Action certification — static inventory",
  "",
  "Generated by `node scripts/action-certification.mjs` from tracked source. " +
  "Presence in a catalog, dispatch, or UI is **not** proof of a working real-host operation.",
  "",
  `- Declared actions: **${rows.length}**`,
  `- READ: **${(counts.READ ?? []).length}**; DRY_RUN: **${(counts.DRY_RUN ?? []).length}**; WRITE: **${(counts.WRITE ?? []).length}**`,
  "- Static parity: backend dispatch and DEMO metadata match. UI routes are syntactic references, not click-through proof.",
  "- Physical real-host execution, UAC, rollback, cancellation, DPI and recovery: **not certified by this inventory**.",
  "",
  "| Action ID | Category | Mode | C# dispatch | DEMO | UI route | Physical operation |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(row => `| ${row.id} | ${row.category} | ${row.mode} | yes | yes | ${row.ui} | Not verified |`),
  "",
  "## Evidence needed for release",
  "",
  "Require representative happy-path + error-path tests, privilege checks, persistence or rollback when declared, " +
  "safe VM execution for WRITE, and physical Windows tests for device-dependent operations. " +
  "Never mark a physical test as passed based on DEMO or static dispatch checks.",
  ""
];
fs.writeFileSync(path.join(root, "docs", "ACTION_CERTIFICATION.md"), lines.join("\n"));
console.log(`ACTION_CERTIFICATION_OK total=${rows.length} read=${(counts.READ ?? []).length} dry_run=${(counts.DRY_RUN ?? []).length} write=${(counts.WRITE ?? []).length}`);
